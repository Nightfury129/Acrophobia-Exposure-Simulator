using System;
using UnityEngine;
using Acrophobia.Telemetry;

namespace Acrophobia.ProceduralEnvironment
{
    /// <summary>
    /// A curtain over the window, built from vertical slats rather than cloth simulation.
    ///
    /// No modelling package is needed. A row of thin scaled boxes reads convincingly as
    /// fabric once each one sways on its own slight phase offset - the eye reads the
    /// differential motion as cloth long before it questions the silhouette. Opening
    /// slides the slats apart and bunches them, which is the motion people actually
    /// recognise, far more than any amount of mesh detail would be.
    ///
    /// It matters more here than decoration. The curtain means the first tier opens with
    /// the drop hidden, so drawing it back is a deliberate act with a real consequence -
    /// the same structure as the balcony door, one step earlier and much gentler. A
    /// participant who is not ready can simply leave it closed and the room stays a room.
    /// </summary>
    public class CurtainController : MonoBehaviour
    {
        [Tooltip("Slats, left to right. Generated by the editor tool.")]
        [SerializeField] private Transform[] _slats = Array.Empty<Transform>();

        [Tooltip("How far each slat travels toward its side when fully open, in metres.")]
        [SerializeField, Range(0.1f, 1.5f)] private float _openTravel = 0.62f;

        [Tooltip("Seconds for a full draw.")]
        [SerializeField, Range(0.4f, 5f)] private float _drawSeconds = 2.2f;

        [Tooltip("Sway amplitude in metres. Small values read as air movement.")]
        [SerializeField, Range(0f, 0.08f)] private float _swayAmplitude = 0.022f;

        [Tooltip("Sway cycles per second.")]
        [SerializeField, Range(0.05f, 1.5f)] private float _swayFrequency = 0.33f;

        [Tooltip("Sway multiplier once the balcony door is open and air is moving.")]
        [SerializeField, Range(1f, 6f)] private float _draughtMultiplier = 2.6f;

        [Tooltip("How close the participant must be to draw it, in metres.")]
        [SerializeField, Range(0.5f, 4f)] private float _reachDistance = 2.0f;

        [SerializeField] private Transform _centerEyeAnchor;
        [SerializeField] private BalconyDoorController _door;
        [SerializeField] private SessionTelemetryLogger _logger;

        private float[] _closedX;
        private float[] _phase;
        private float _openAmount;      // 0 closed, 1 open
        private float _targetOpen;
        private bool _captured;

        public bool IsOpen => _openAmount > 0.5f;

        public float OpenAmount => _openAmount;

        public event Action OnCurtainOpened;

        public event Action OnCurtainClosed;

        private void Awake()
        {
            ResolveReferences();
            CaptureRest();
        }

        public void ResolveReferences()
        {
            if (_door == null) _door = FindAnyObjectByType<BalconyDoorController>();
            if (_logger == null) _logger = FindAnyObjectByType<SessionTelemetryLogger>();

            if (_centerEyeAnchor == null)
            {
                var found = GameObject.Find("CenterEyeAnchor");
                if (found != null) _centerEyeAnchor = found.transform;
                else if (Camera.main != null) _centerEyeAnchor = Camera.main.transform;
            }
        }

        /// <summary>
        /// Records where each slat rests, so sway and opening are both offsets from a
        /// fixed origin and cannot accumulate drift over a long session.
        /// </summary>
        private void CaptureRest()
        {
            if (_captured || _slats == null || _slats.Length == 0) return;

            _closedX = new float[_slats.Length];
            _phase = new float[_slats.Length];

            for (int i = 0; i < _slats.Length; i++)
            {
                if (_slats[i] == null) continue;
                _closedX[i] = _slats[i].localPosition.x;

                // Irrational-ish stride keeps neighbouring slats from syncing up, which
                // is what would make the row read as a solid board instead of cloth.
                _phase[i] = i * 0.7913f;
            }

            _captured = true;
        }

        public void Open()
        {
            if (_targetOpen > 0.5f) return;
            _targetOpen = 1f;
            _logger?.RecordEvent("curtain_opened", 0, "participant_initiated", 0f);
            OnCurtainOpened?.Invoke();
        }

        public void Close()
        {
            if (_targetOpen < 0.5f) return;
            _targetOpen = 0f;
            _logger?.RecordEvent("curtain_closed", 0, "participant_initiated", 0f);
            OnCurtainClosed?.Invoke();
        }

        public void Toggle()
        {
            if (IsOpen) Close(); else Open();
        }

        public void SetSlats(Transform[] slats)
        {
            _slats = slats;
            _captured = false;
            CaptureRest();
        }

        public bool IsWithinReach
        {
            get
            {
                if (_centerEyeAnchor == null || _slats == null || _slats.Length == 0) return false;

                Transform mid = _slats[_slats.Length / 2];
                if (mid == null) return false;

                Vector3 a = _centerEyeAnchor.position, b = mid.position;
                float dx = a.x - b.x, dz = a.z - b.z;
                return Mathf.Sqrt(dx * dx + dz * dz) <= _reachDistance;
            }
        }

        // Same interaction as the balcony door, so there is one verb to learn rather
        // than two. Nothing opens the curtain on the participant's behalf.
        private bool WasInteractPressed()
        {
            try
            {
                if (OVRInput.GetDown(OVRInput.Button.PrimaryIndexTrigger) ||
                    OVRInput.GetDown(OVRInput.Button.SecondaryIndexTrigger) ||
                    OVRInput.GetDown(OVRInput.Button.One))
                {
                    return true;
                }
            }
            catch (Exception) { }

#if ENABLE_INPUT_SYSTEM
            try
            {
                var kb = UnityEngine.InputSystem.Keyboard.current;
                if (kb != null && (kb.eKey.wasPressedThisFrame || kb.spaceKey.wasPressedThisFrame))
                {
                    return true;
                }
            }
            catch (Exception) { }
#endif

#if ENABLE_LEGACY_INPUT_MANAGER
            try
            {
                if (Input.GetKeyDown(KeyCode.E) || Input.GetKeyDown(KeyCode.Space)) return true;
            }
            catch (Exception) { }
#endif

            return false;
        }

        private void Update()
        {
            CaptureRest();

            if (IsWithinReach && WasInteractPressed())
            {
                Toggle();
            }

            if (_slats == null || _slats.Length == 0 || _closedX == null) return;

            if (!Mathf.Approximately(_openAmount, _targetOpen))
            {
                float step = Time.deltaTime / Mathf.Max(0.05f, _drawSeconds);
                _openAmount = Mathf.MoveTowards(_openAmount, _targetOpen, step);
            }

            float draught = (_door != null && _door.IsOpen) ? _draughtMultiplier : 1f;
            float t = Time.time * _swayFrequency * Mathf.PI * 2f;
            int count = _slats.Length;
            float half = (count - 1) * 0.5f;

            for (int i = 0; i < count; i++)
            {
                Transform slat = _slats[i];
                if (slat == null) continue;

                // Slats part toward whichever side they started on, and bunch as they go:
                // the further a slat travels, the closer it sits to its neighbours.
                float side = (i - half) >= 0f ? 1f : -1f;
                float normalised = Mathf.Abs(i - half) / Mathf.Max(1f, half);
                float travel = _openTravel * _openAmount * (0.35f + 0.65f * normalised);

                // Sway dies off as the curtain opens, since a bunched curtain barely moves.
                float swayScale = Mathf.Lerp(1f, 0.25f, _openAmount);
                float sway = Mathf.Sin(t + _phase[i]) * _swayAmplitude * draught * swayScale;

                Vector3 p = slat.localPosition;
                p.x = _closedX[i] + side * travel + sway;
                p.z = Mathf.Sin(t * 0.73f + _phase[i]) * _swayAmplitude * 0.45f * draught * swayScale;
                slat.localPosition = p;
            }
        }
    }
}
